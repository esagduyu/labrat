"""Spider2-DBT AutoResearch Loop
=================================

Autonomous prompt optimisation loop for Spider2-DBT using DSPy + MIPROv2.
Inspired by Karpathy's autoresearch (github.com/karpathy/autoresearch).

How it works
------------
1. Create a git branch  autoresearch/<tag>
2. Run baseline eval on a small dev set (~12 tasks)
3. Run MIPROv2 to propose better instructions for the DSPy module
4. Re-eval with optimised module
5. If score improved  → save, git commit, append to findings.md
   If not             → discard, append "no improvement" to findings.md
6. LOOP FOREVER until you kill it

Usage
-----
    # One-time setup: download spider2-dbt source databases first
    #   cd ~/repos/Spider2/spider2-dbt
    #   pip install gdown
    #   gdown 'https://drive.google.com/uc?id=1N3f7BSWC4foj-V-1C9n8M2XmgV7FOcqL'
    #   gdown 'https://drive.google.com/uc?id=1s0USV_iQLo4oe05QqAMnhGGp5jeejCzp'
    #   python setup.py

    uv run scripts/autoresearch_spider2.py

    # Optional flags:
    #   --run-tag  may24     (default: today, e.g. "may23")
    #   --dev-set  12        (number of tasks for fast iteration, default 12)
    #   --max-iters 0        (0 = run forever, default 0)
    #   --full-eval          (also run all 68 tasks after each keep)

Environment
-----------
    ANTHROPIC_API_KEY   required
    SPIDER2_DATA_DIR    path to Spider2 repo clone (default: ~/repos/Spider2)
"""

